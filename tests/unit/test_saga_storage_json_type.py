"""DDL and value handling of the saga storage JSON column.

The `context` column of `SagaExecutionModel` was moved from `sqlalchemy.JSON` to
`cqrs.sqlalchemy_types.JSONType`. The type is an extension point only: by
default it must render exactly the DDL that `sqlalchemy.JSON` rendered before,
on every dialect. The reference DDL strings below were captured from the model
before the change and are compared as whole statements, which is the backward
compatibility criterion of the change.
"""

import json
import typing

import pytest
import sqlalchemy
from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateTable

from cqrs.saga.storage.sqlalchemy import (
    SAGA_EXECUTION_TABLE_NAME,
    SAGA_LOG_TABLE_NAME,
    Base,
)
from cqrs.sqlalchemy_types import (
    Binary16,
    DialectTypeHandler,
    JSONType,
    UUIDBinary,
)

